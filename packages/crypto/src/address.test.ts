// Real-world mainnet test vectors from the live mempool dump. Each row is
// taken from one tx in
// a live node's `/api/mempool/recent` and re-encoded with this base's
// magic — encoding-level goldens. These are the most
// authoritative test vectors we have — if our implementation produces
// the same address as the node from the same pubkey, we're byte-compat.

interface PubkeyVector {
  pubkey: string;
  scripthash: string;
  address: string;
}

